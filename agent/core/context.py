"""
文件职能: 共享上下文注入 —— 当前日期 + 「检索结果优先于模型内部知识」的 grounding 说明。
解决：模型训练数据有截止日期，容易把知识库里较新的商品/政策误判为「未来/伪造」。
"""
from datetime import datetime


def current_date_cn() -> str:
    """返回中文日期，如「2026年10月06日」。"""
    return datetime.now().strftime("%Y年%m月%d日")


def retrieval_grounding_note() -> str:
    """「以检索结果为准」的说明，注入到 RAG Agent 的系统提示词。"""
    return (
        f"【强制要求】当前日期是 {current_date_cn()}，你的训练数据已过时，其中「最新产品」的判断不可信。"
        "知识库检索到的商品/政策信息是店铺当前真实在售的最新资料，请直接依据检索结果回答；"
        "严禁用你过时的内部知识去质疑检索结果，严禁说「该型号不存在/这是伪造/未来/虚构信息」。"
        "你只负责如实转述检索到的参数与特性。"
    )
